-- persimmon-ddd outbox schema for PostgreSQL and H2. Run it with your migration tool.
CREATE TABLE IF NOT EXISTS persimmon_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR(64)  NOT NULL UNIQUE,
    source          VARCHAR(255) NOT NULL,
    type            VARCHAR(512) NOT NULL,
    version         INT          NOT NULL,
    payload         TEXT         NOT NULL,
    occurred_at     TIMESTAMP    NOT NULL,
    subject         VARCHAR(255),
    correlation_id  VARCHAR(64)  NOT NULL,
    causation_id    VARCHAR(64),
    destination     VARCHAR(255),
    sent            BOOLEAN      NOT NULL DEFAULT FALSE,
    sent_at         TIMESTAMP,
    attempts        INT          NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP,
    lease_token     VARCHAR(64),
    lease_until     TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_persimmon_outbox_unsent ON persimmon_outbox (sent, next_attempt_at, created_at);
CREATE INDEX IF NOT EXISTS idx_persimmon_outbox_subject ON persimmon_outbox (subject, sent, created_at, id);
CREATE INDEX IF NOT EXISTS idx_persimmon_outbox_lease ON persimmon_outbox (lease_token);

CREATE TABLE IF NOT EXISTS persimmon_dead_letter (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR(64)  NOT NULL UNIQUE,
    source          VARCHAR(255) NOT NULL,
    type            VARCHAR(512) NOT NULL,
    version         INT          NOT NULL,
    payload         TEXT         NOT NULL,
    occurred_at     TIMESTAMP    NOT NULL,
    subject         VARCHAR(255),
    correlation_id  VARCHAR(64)  NOT NULL,
    causation_id    VARCHAR(64),
    destination     VARCHAR(255),
    attempts        INT          NOT NULL,
    reason          VARCHAR(32)  NOT NULL,
    last_error      TEXT,
    failed_at       TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS persimmon_inbox (
    consumer     VARCHAR(128) NOT NULL,
    source       VARCHAR(255) NOT NULL,
    message_key  VARCHAR(128) NOT NULL,
    processed_at TIMESTAMP    NOT NULL,
    PRIMARY KEY (consumer, source, message_key)
);
CREATE INDEX IF NOT EXISTS idx_persimmon_inbox_processed_at ON persimmon_inbox (processed_at);
